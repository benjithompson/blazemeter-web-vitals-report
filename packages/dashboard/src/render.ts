/** Render the whole report as one self-contained HTML document: static
 *  header, Engines and fallback summary; the data blob; the browser bundle,
 *  which replaces the summary with the interactive report on load. */
export function renderHtml(data: ReportData): string {
  // The Report name is the title; the master id stays visible in the link line
  // beneath it, so the id is never lost. Falls back to the id when unnamed, and
  // to the local source when there is no id. A local import with no id has no
  // BlazeMeter Report to link to, so it gets no link rather than a broken one.
  const heading =
    data.reportName ?? `${S.title} ${data.masterId ?? data.localSource ?? ''}`.trimEnd();
  const reportUrl = data.masterId === null ? null : masterReportUrl(data.masterId);
  const reportLinkHtml =
    reportUrl === null
      ? ''
      : `<p class="report-link"><a href="${escapeHtml(reportUrl)}" title="${escapeHtml(
          reportUrl,
        )}">${escapeHtml(`${S.reportLink} ↗`)}</a></p>\n`;
  const metaLine = [
    data.masterId === null ? null : `${S.reportWord} ${data.masterId}`,
    data.localSource === undefined ? null : `${S.importedFrom} ${data.localSource}`,
    `${S.generated} ${data.generatedAt}`,
    sampleEngineCountText(data.samples.length, data.sessions.length),
  ]
    .filter((part) => part !== null)
    .join(' · ');

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="${CSP}">
<meta name="referrer" content="no-referrer">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(heading)}</title>
<style>${STYLE}</style>
</head>
<body>
<header>
<h1>${escapeHtml(heading)}</h1>
${reportLinkHtml}<p class="meta">${escapeHtml(metaLine)}</p>
</header>
${enginesHtml(data.sessions)}
<section>
<h2>${escapeHtml(S.routesHeading)}<span class="badge">${escapeHtml(S.labData)}</span></h2>
<noscript><p class="status-note">${escapeHtml(S.noscriptNote)}</p></noscript>
<p id="${STATUS_ID}" class="status-note" hidden></p>
<div id="${APP_ID}" data-bzm-state="static">${routeSummaryHtml(buildRouteSummary(data))}</div>
</section>
<div id="bzm-tip" role="tooltip" hidden></div>
<script type="application/gzip" data-encoding="base64" id="${DATA_BLOB_ID}">${encodeBlob(data)}</script>
<script>${BROWSER_BUNDLE}</script>
</body>
</html>
`;
}
