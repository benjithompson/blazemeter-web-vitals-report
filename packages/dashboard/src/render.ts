// The BlazeMeter Report (master) page. An <a href> is a user-initiated
// navigation, never a fetch — the file stays self-contained (nothing is
// requested to render it), and the link points at the live Report on demand.
const REPORT_URL_BASE = 'https://a.blazemeter.com/app/#/masters';
function masterReportUrl(masterId: string): string {
  return `${REPORT_URL_BASE}/${masterId}/summary`;
}

/** The data blob's payload: JSON → gzip → base64. Base64's alphabet holds no
 *  "<", so the payload can never close its <script> element. */
export function encodeBlob(data: ReportData): string {
  return gzipSync(Buffer.from(JSON.stringify(data), 'utf8')).toString('base64');
}

// ------------------------------------------------------------ page chrome

// The page's own guard for "zero external requests": everything is inline
// (the <style>, the one <script>, inline SVG), so the browser may fetch
// nothing. The data blob is never executed (its type is not a script type),
// so script-src does not apply to it; `img-src data:` is the only allowance,
// for future inline images. Declared first in <head>, before the <style> and
// <script> it governs. The browser bundle needs no more: it decompresses an
// in-memory stream, never a blob:/data: URL, and starts no worker.
const CSP =
  "default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; img-src data:";

