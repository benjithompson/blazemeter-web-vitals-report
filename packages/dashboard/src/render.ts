// The emitter — ONE self-contained static HTML file, rendered in the browser.
//
// The file carries three things, all inline:
//   1. the data, ONCE: the ReportData (attributed Samples, Outcomes, sessions,
//      Route rows) as gzip-compressed, base64-encoded JSON in
//      <script type="application/gzip" data-encoding="base64" id="bzm-vitals-data">.
//      That blob is a PRODUCT requirement, not a test hook: the pre-signed
//      dataUrl expires in 20 minutes, so the data must be baked in at build
//      time for the artifact to be permanent. Seam 2 decodes it back out;
//   2. the code, ONCE: src/browser/entry.ts bundled by esbuild (BROWSER_BUNDLE,
//      generated by scripts/build-browser.ts) — the same view-model.ts and
//      markup (browser/views.ts) Node runs. The browser unpacks the blob with
//      DecompressionStream('gzip'), builds the view, and renders it; the
//      include/exclude toggle recomputes in the browser;
//   3. a small server-rendered FALLBACK: the Route table at p75 with coverage,
//      plus a <noscript> note, so the Report still says something if
//      JavaScript is off, DecompressionStream is missing, or the render fails.
//
// The file size now grows with the data (compressed), not with
// Samples × charts × variants: nothing is pre-rendered per Sample.
//
// Hard rules, asserted on the emitted bytes by the tests:
//   - ZERO external requests: no <script src>, <link href>, <img src>, no
//     fetch/XHR, no blob:/data: URL, no worker — the file renders offline, in
//     six months, unchanged; the <head> CSP meta makes the browser enforce it
//     (test/csp.test.ts);
//   - NO credentials and NO pre-signed URLs, ever;
//   - a Report with zero vitals says "no samples", never 0.

