#!/usr/bin/env tsx
// Builds the report's ONE inline <script>: esbuild bundles src/browser/entry.ts — the
// view model and markup code Node runs, unchanged — for the browser, and writes it as a string
// constant into src/browser/bundle.generated.ts, which render.ts imports. Generated, gitignored,
// and rebuilt from the real sources by everything that needs it, before it is needed:
//   npm run build:browser                  (this file)
//   npm run typecheck / build              (root and dashboard: before tsc --build)
//   npm test                               (vitest globalSetup: test/global-setup.ts)
//   npm run build:standalone               (scripts/build-standalone.ts, before bundling cli.ts)
// The build FAILS if the bundle would import anything (platform 'browser' cannot resolve
// node:*, so view-model.ts stays isomorphic), or if the code could close its <script> early.

import { build, type Plugin } from 'esbuild';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const DASHBOARD_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');
const FORMAT_SRC = join(DASHBOARD_DIR, '..', 'format', 'src', 'index.ts');
const ENTRY = join(DASHBOARD_DIR, 'src', 'browser', 'entry.ts');
export const BUNDLE_MODULE = join(DASHBOARD_DIR, 'src', 'browser', 'bundle.generated.ts');

/** Resolve the workspace format package to its source file — never a stale (or absent) dist/. */
export const formatFromSource: Plugin = {
  name: 'bzm-vitals-format-from-source',
  setup: (b) => void b.onResolve({ filter: /^bzm-vitals-format$/ }, () => ({ path: FORMAT_SRC })),
};

/** Bundle the browser entry to one minified IIFE; throws on any import or unsafe sequence. */
export async function bundleBrowser(entry = ENTRY): Promise<string> {
  const { metafile, outputFiles } = await build({
    entryPoints: [entry], bundle: true, platform: 'browser', format: 'iife', target: 'es2020',
    minify: true, legalComments: 'none', charset: 'ascii', plugins: [formatFromSource],
    write: false, metafile: true, logLevel: 'silent', outfile: 'bundle.js',
  });
  const imports = Object.values(metafile.outputs).flatMap((o) => o.imports.map((i) => i.path));
  if (imports.length > 0) throw new Error(`browser bundle imports ${imports.join(', ')}; it must be self-contained`);
  const code = outputFiles[0]!.text.trim();
  // Inside <script>, "</script" ends the element and "<!--" changes how it is parsed.
  if (/<\/script|<!--/i.test(code)) throw new Error('browser bundle contains "</script" or "<!--"');
  return code;
}

/** Regenerate src/browser/bundle.generated.ts; rewrites it (atomically) only on change. */
export async function buildBrowserBundle(): Promise<{ outFile: string; bytes: number; changed: boolean }> {
  const code = await bundleBrowser();
  const source = [
    '// GENERATED by packages/dashboard/scripts/build-browser.ts (npm run build:browser). DO NOT EDIT.',
    '// The report\'s inline <script>: src/browser/entry.ts bundled for the browser by esbuild.',
    `export const BROWSER_BUNDLE: string = ${JSON.stringify(code)};`,
    '',
  ].join('\n');
  const current = await readFile(BUNDLE_MODULE, 'utf8').catch(() => null);
  if (current === source) return { outFile: BUNDLE_MODULE, bytes: code.length, changed: false };
  await mkdir(dirname(BUNDLE_MODULE), { recursive: true });
  const tmp = `${BUNDLE_MODULE}.${process.pid}.tmp`;
  await writeFile(tmp, source, 'utf8');
  await rename(tmp, BUNDLE_MODULE);
  return { outFile: BUNDLE_MODULE, bytes: code.length, changed: true };
}

// CLI entry (npm run build:browser). Guarded so the harness can import buildBrowserBundle.
if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  buildBrowserBundle()
    .then(({ outFile, bytes, changed }) => console.log(`browser bundle ${changed ? 'written' : 'up to date'}: ${outFile} (${bytes} bytes)`))
    .catch((err) => (console.error(err), process.exit(1)));
}
